/** Product display names as the example writes them. */
export function ugcProductLabel(product: string): string {
  switch (product) {
    case 'EasyStretch':
      return 'Viasox EasyStretch™ Socks';
    case 'Compression':
      return 'Viasox Compression Socks';
    case 'Ankle Compression':
      return 'Viasox Ankle Compression Socks';
    default:
      return `Viasox ${product}`;
  }
}

export function ugcDurationLabel(duration: string): string {
  switch (duration) {
    case '1-15 sec':
      return '1–15 seconds';
    case '16-59 sec':
      return '16–59 seconds';
    case '60-90 sec':
      return '60–90 seconds';
    default:
      return duration;
  }
}

/** Main-edit rows only (before the end card): the hook 1 row, the body, the
 *  CTA row. Alternate-take rows are represented by the hooks list instead. */
function mainEditRows(brief: UgcBriefV2): V2Row[] {
  const endIdx = brief.storyboard.findIndex((r) => r.clipNumber === 'end-card');
  return endIdx === -1 ? brief.storyboard : brief.storyboard.slice(0, endIdx);
}

/** The script table rows: HOOK 1..N (each hook is its own take, sharing the
 *  hook clip's shot direction unless its alternate-take row carries its own),
 *  then BODY 1..n, OFFER (when a row is marked), CTA. */
export function buildScriptRows(brief: UgcBriefV2): UgcScriptRow[] {
  const rows = mainEditRows(brief);
  const primaryHookId = brief.hooks[0]?.id;
  const primaryCtaId = brief.ctas[0]?.id;
  const hookRow = rows.find((r) => r.mirrorsLineId === primaryHookId) ?? rows[0];
  const ctaRow = rows.find((r) => r.mirrorsLineId === primaryCtaId);
  const out: UgcScriptRow[] = [];

  brief.hooks.forEach((h, i) => {
    const takeRow = i === 0 ? hookRow : brief.storyboard.find((r) => r.mirrorsLineId === h.id);
    const shot = (takeRow?.shotDescription ?? hookRow?.shotDescription ?? '').replace(/^Same setup as clip 1\.\s*/i, '');
    const overlay = takeRow?.overlayText ?? (i === 0 ? hookRow?.overlayText : '') ?? '';
    out.push({
      label: `HOOK ${i + 1}${i === brief.hooks.length - 1 && brief.hooks.length === 4 && /\b(sale|free|offer|anniversary|deal)\b/i.test(h.text) && hasOffer(brief) ? ' — SALE FIRST' : ''}`,
      shot,
      line: h.text,
      overlay,
    });
  });

  let bodyNo = 0;
  let productSeen = false;
  for (const r of rows) {
    if (r === hookRow || r.mirrorsLineId === primaryHookId) continue;
    if (r === ctaRow || r.mirrorsLineId === primaryCtaId) continue;
    if (r.isOffer) {
      out.push({ label: 'OFFER', shot: r.shotDescription, line: r.scriptLine, overlay: r.overlayText ?? '' });
      continue;
    }
    bodyNo += 1;
    const reveal = !productSeen && r.isProductReveal;
    if (reveal) productSeen = true;
    out.push({
      label: `BODY ${bodyNo}${reveal ? ' — PRODUCT REVEAL' : ''}`,
      shot: r.shotDescription,
      line: r.scriptLine,
      overlay: r.overlayText ?? '',
    });
  }
  if (ctaRow) {
    out.push({ label: 'CTA', shot: ctaRow.shotDescription, line: ctaRow.scriptLine, overlay: ctaRow.overlayText ?? '' });
  } else if (brief.ctas[0]) {
    out.push({ label: 'CTA', shot: '', line: brief.ctas[0].text, overlay: '' });
  }
  return out;
}

function hasOffer(brief: UgcBriefV2): boolean {
  return Boolean(brief.creatorDoc?.strategy.offer?.promo);
}

/** Map a finished UGC brief onto the three-tab document. Throws for ecom
 *  briefs (they keep their own export) and for briefs written before the
 *  document layer existed (no `creatorDoc`). */
export function buildUgcDocument(brief: UgcBriefV2): UgcDocument {
  if (taskAdType(brief.task) === 'ecom') throw new Error('The three-tab creator document is UGC-only.');
  const doc = brief.creatorDoc;
  if (!doc) {
    throw new Error(
      'This brief was written before the three-tab document format existed and has no document fields. Regenerate it (or use "Rework story") to get the new format.',
    );
  }
  const title = brief.taskName;

  const creatorBrief: UgcDocTab = {
    title: 'Creator Brief',
    blocks: [
      { kind: 'title', text: 'Creator Brief' },
      { kind: 'heading', text: 'BRIEF INFO' },
      { kind: 'paragraph', text: '' },
      {
        kind: 'kvTable',
        rows: [
          { label: 'Brief ID', value: [title] },
          { label: 'Product', value: [ugcProductLabel(brief.task.product)] },
          { label: 'Collection', value: [doc.briefInfo.collection] },
          { label: 'Socks', value: [doc.briefInfo.socks] },
          { label: 'Format', value: [doc.briefInfo.format] },
          { label: 'Creator Requirement', value: [doc.briefInfo.creatorRequirement] },
          { label: 'Creator Note', value: interleaveBlank(doc.briefInfo.creatorNote) },
          { label: 'Duration', value: [ugcDurationLabel(brief.task.duration)] },
        ],
      },
    ],
  };

  const script: UgcDocTab = {
    title: 'Script',
    blocks: [
      { kind: 'title', text: 'Script' },
      { kind: 'heading', text: 'CREATOR NOTE' },
      { kind: 'paragraph', text: doc.scriptNote },
      { kind: 'paragraph', text: '' },
      { kind: 'readThroughLabel', text: 'SCRIPT — FULL READ-THROUGH' },
      { kind: 'readThrough', text: brief.scriptProse },
      { kind: 'heading', text: 'SCRIPT' },
      { kind: 'paragraph', text: '' },
      {
        kind: 'scriptTable',
        header: ['LINE / SECTION', 'SHOT / ACTION', 'SCRIPT LINE', 'ON-SCREEN TEXT'],
        rows: buildScriptRows(brief),
      },
      { kind: 'heading', text: 'BEFORE YOU SUBMIT' },
      { kind: 'bullets', items: doc.beforeYouSubmit },
    ],
  };

  const groups: UgcStrategyGroup[] = [
    {
      section: 'Strategy',
      fields: [
        { field: 'Awareness Level', direction: doc.strategy.awarenessLevel },
        { field: 'Primary Emotion', direction: doc.strategy.primaryEmotion },
        { field: 'Avatar', direction: doc.strategy.avatar },
        { field: 'Hypothesis', direction: doc.strategy.hypothesis },
        { field: 'Core Creative Idea', direction: doc.strategy.coreCreativeIdea },
      ],
    },
  ];
  if (doc.strategy.offer?.promo) {
    groups.push({
      section: 'Offer',
      fields: [
        { field: 'Promo', direction: doc.strategy.offer.promo },
        { field: 'Value Callout', direction: doc.strategy.offer.valueCallout },
        { field: 'Fourth Hook', direction: doc.strategy.offer.fourthHook },
        { field: 'Urgency', direction: doc.strategy.offer.urgency },
      ],
    });
  }
  groups.push(
    {
      section: 'Production',
      fields: [
        { field: 'Format', direction: doc.strategy.production.format },
        { field: 'Creator', direction: doc.strategy.production.creator },
        { field: 'Props', direction: doc.strategy.production.props },
        { field: 'Locations', direction: doc.strategy.production.locations },
      ],
    },
    {
      section: 'Editing',
      fields: [
        { field: 'Pacing', direction: doc.strategy.editing.pacing },
        { field: 'Graphics', direction: doc.strategy.editing.graphics },
        { field: 'Audio', direction: doc.strategy.editing.audio },
      ],
    },
  );
  if (doc.strategy.reference?.adaptationNote) {
    groups.push({ section: 'Reference', fields: [{ field: 'Adaptation Note', direction: doc.strategy.reference.adaptationNote }] });
  }

  const strategy: UgcDocTab = {
    title: 'Strategy',
    blocks: [
      { kind: 'title', text: 'Strategy' },
      { kind: 'heading', text: 'STRATEGY' },
      { kind: 'paragraph', text: '' },
      { kind: 'strategyTable', header: ['SECTION', 'FIELD', 'DIRECTION'], groups },
    ],
  };

  return { title, tabs: [creatorBrief, script, strategy] };
}

/** ["a","b","c"] → ["a","","b","","c"] — blank paragraphs between, as in the example. */
function interleaveBlank(paragraphs: string[]): string[] {
  const out: string[] = [];
  paragraphs.forEach((p, i) => {
    if (i > 0) out.push('');
    out.push(p);
  });
  return out.length ? out : [''];
}

