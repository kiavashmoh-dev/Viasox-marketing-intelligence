export function getUgcDocField(doc: UgcCreatorDoc, path: UgcDocFieldPath): string | string[] | undefined {
  let cur: unknown = doc;
  for (const key of path.split('.')) {
    if (cur === null || typeof cur !== 'object') return undefined;
    cur = (cur as Record<string, unknown>)[key];
  }
  return cur as string | string[] | undefined;
}

/** Returns a NEW doc with the field set (creates the optional offer /
 *  reference groups on demand). */
export function setUgcDocField(doc: UgcCreatorDoc, path: UgcDocFieldPath, value: string | string[]): UgcCreatorDoc {
  const next = JSON.parse(JSON.stringify(doc)) as UgcCreatorDoc;
  const keys = path.split('.');
  let cur = next as unknown as Record<string, unknown>;
  for (const key of keys.slice(0, -1)) {
    if (cur[key] === undefined || cur[key] === null || typeof cur[key] !== 'object') cur[key] = {};
    cur = cur[key] as Record<string, unknown>;
  }
  cur[keys[keys.length - 1]] = value;
  return next;
}

