/**
 * The UGC creator document — the three-tab brief format (Sep 2026).
 *
 * Kia's decision: every UGC brief ships as ONE Google Doc with THREE tabs
 * (Creator Brief · Script · Strategy), in the exact style of the reference
 * document `docxTemplate/EXAMPLE-UGC-brief.docx` (a Google Docs export):
 * same fonts, sizes, colors, borders, shading, margins, and — above all —
 * the same trimmed level of information. Nothing more, nothing less.
 *
 * This file is the RENDERER-AGNOSTIC model: a document is tabs of blocks.
 * Two renderers consume it —
 *   · `ugcDocx.ts`       → a real .docx (download), cloned from the example's
 *                          own XML so the formatting is byte-for-byte the same
 *   · `../api/googleDocs.ts` → a Google Doc with real tabs via the Docs API
 * and `buildUgcDocument()` (below) maps a finished UgcBriefV2 onto it.
 *
 * STYLE SPEC (measured from the example; every renderer reproduces it):
 *   Page          A4 portrait (595.3 × 841.9 pt); margins top/bottom 3 cm
 *                 (85.05 pt), left/right 2 cm (56.7 pt).
 *   Base font     Arial 11 pt, black; body line spacing 1.15.
 *   title         Tab title paragraph — 26 pt, regular, black, spacing 0.
 *   heading       Heading 1 — bold, 16 pt, color #203f66, 8 pt before + after.
 *   paragraph     Normal — 11 pt, regular.
 *   readThroughLabel  bold 12 pt; 16.5 pt before, 7.5 pt after; single spacing.
 *   readThrough   10 pt on a #f8f9fb shaded run; line spacing 1.5;
 *                 7.5 pt before, 19.5 pt after; right indent 10.5 pt.
 *   bullets       ● list, 9 pt; left indent 36 pt, hanging 18 pt.
 *   kvTable       2 columns × 241 pt; 1 pt black borders (all); label cells
 *                 shaded #edf2fa, bold 9 pt; value cells 9 pt; single spacing.
 *   scriptTable   4 columns × 120.5 pt; header row shaded #203f66, bold white
 *                 8 pt; LINE/SECTION and SHOT/ACTION cells bold 8 pt; SCRIPT
 *                 LINE and ON-SCREEN TEXT cells 8 pt.
 *   strategyTable 3 columns × 160.67 pt; header row shaded #203f66, bold white
 *                 9 pt; SECTION column merged vertically per group, bold 9 pt;
 *                 FIELD column bold 9 pt; DIRECTION column 9 pt; every body row
 *                 at least 19 pt tall.
 */

import type { UgcBriefV2, V2Row } from './v2Types';
import { taskAdType } from './v2Types';

// ─── The model ──────────────────────────────────────────────────────────────

export interface UgcDocument {
  /** The file / Google Doc name (= the task name). */
  title: string;
  tabs: [UgcDocTab, UgcDocTab, UgcDocTab];
}

export interface UgcDocTab {
  /** Tab name in Google Docs; also rendered as the tab's title paragraph. */
  title: string;
  blocks: UgcDocBlock[];
}

export type UgcDocBlock =
  | { kind: 'title'; text: string }
  | { kind: 'heading'; text: string }
  | { kind: 'paragraph'; text: string }
  | { kind: 'readThroughLabel'; text: string }
  | { kind: 'readThrough'; text: string }
  | { kind: 'bullets'; items: string[] }
  | { kind: 'kvTable'; rows: UgcKvRow[] }
  | { kind: 'scriptTable'; header: [string, string, string, string]; rows: UgcScriptRow[] }
  | { kind: 'strategyTable'; header: [string, string, string]; groups: UgcStrategyGroup[] };

export interface UgcKvRow {
  label: string;
  /** Paragraphs of the value cell. An empty string is a blank paragraph
   *  (the example separates the creator-note paragraphs with blank lines). */
  value: string[];
}

export interface UgcScriptRow {
  /** LINE / SECTION — e.g. "HOOK 1", "HOOK 4 — SALE FIRST", "BODY 5 — PRODUCT REVEAL", "OFFER", "CTA". */
  label: string;
  shot: string;
  line: string;
  /** ON-SCREEN TEXT — empty for most body lines. */
  overlay: string;
}

export interface UgcStrategyGroup {
  /** SECTION cell, merged down the group: "Strategy" | "Offer" | "Production" | "Editing" | "Reference". */
  section: string;
  fields: Array<{ field: string; direction: string }>;
}

// ─── The brief's document fields (generated by the writer, edited in-app) ───

/** The fields of the three-tab document that the brief object must carry
 *  beyond hooks / CTAs / prose / storyboard. Generated by the UGC writer in
 *  the same call as the script (calibrated on the example document), shown
 *  and regenerable in the editor, rendered by `buildUgcDocument`. */
export interface UgcCreatorDoc {
  /** Creator Brief tab → BRIEF INFO. */
  briefInfo: {
    /** e.g. "EasyStretch™" */
    collection: string;
    /** The exact socks / patterns the creator receives, e.g. "2 EasyStretch Socks — Legacy and Snoopy pattern". */
    socks: string;
    /** e.g. "9:16 creator-filmed UGC demonstration + testimonial" */
    format: string;
    /** Who the creator must be, one line. */
    creatorRequirement: string;
    /** The friendly note to the creator — 3-4 short paragraphs. */
    creatorNote: string[];
  };
  /** Script tab → CREATOR NOTE (one short paragraph) + BEFORE YOU SUBMIT (bullets). */
  scriptNote: string;
  beforeYouSubmit: string[];
  /** Strategy tab. */
  strategy: {
    awarenessLevel: string;
    primaryEmotion: string;
    avatar: string;
    hypothesis: string;
    coreCreativeIdea: string;
    /** Present only when a promotion is running in this batch. */
    offer?: {
      promo: string;
      valueCallout: string;
      fourthHook: string;
      urgency: string;
    };
    production: {
      format: string;
      creator: string;
      props: string;
      locations: string;
    };
    editing: {
      pacing: string;
      graphics: string;
      audio: string;
    };
    /** Present only when an Inspiration Bank example is pinned to the task. */
    reference?: {
      adaptationNote: string;
    };
  };
}

